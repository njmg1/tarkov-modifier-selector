#!/usr/bin/env python3
"""Crop the 62 UNTAR CONTROL card icons out of the season-2 community sheet,
key them out to alpha, and emit icons.js (data URIs).

Run from docs/season2/:  python3 build_icons_s2.py <source.png>

Same approach as season 1's build_icons.py: the icons are white line art on a
tinted, dot-hatched plate, so a luminance threshold taken from the whole card
(not the crop) separates stroke from plate.
"""
import base64, io, os, sys
import numpy as np
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    '~/Downloads/untar_control_original_template_korean_final_v2_1.png')
OUT_JS = 'icons.js'

COLS = [82, 1014, 1946]          # card x per column
GLOBAL = [509, 648]              # card y per row
POS = [888, 1027, 1166, 1304, 1442, 1580, 1718, 1856, 1994, 2132, 2270]
NEG = [2530, 2668, 2808, 2946, 3087, 3224, 3364, 3502, 3640]
CW, CH = 912, 122
BOX = (10, 4, 128, 122)          # icon plate inside the card (118x118)

im = Image.open(SRC).convert('RGB')


def cards(rows, total):
    out = []
    for y in rows:
        for x in COLS:
            if len(out) < total:
                out.append((x, y - 3))
    return out


def keyed_alpha(x, y):
    full = np.array(im.crop((x, y, x + CW, y + CH)).convert('L'), dtype=float)
    bg = full[full <= np.percentile(full, 60)]
    t0 = bg.mean() + 4.0 * bg.std()
    lum = full[BOX[1]:BOX[3], BOX[0]:BOX[2]]
    t1 = np.percentile(lum, 99.0)
    alpha = (np.clip((lum - t0) / max(t1 - t0, 1e-6), 0, 1) * 255).astype(np.uint8)
    rgba = np.zeros((*lum.shape, 4), np.uint8)
    rgba[..., :3] = 255
    rgba[..., 3] = alpha
    return Image.fromarray(rgba, 'RGBA')


boxes = cards(GLOBAL, 6) + cards(POS, 31) + cards(NEG, 25)
assert len(boxes) == 62, len(boxes)

rows, total = [], 0
for i, (x, y) in enumerate(boxes, start=1):
    buf = io.BytesIO()
    keyed_alpha(x, y).save(buf, format='PNG', optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode()
    total += len(b64)
    rows.append(f"  {i}: 'data:image/png;base64,{b64}',")

with open(OUT_JS, 'w') as fh:
    fh.write(
        '// GENERATED by build_icons_s2.py — do not edit.\n'
        '// Source: the UNTAR CONTROL community card sheet (2936x4094 PNG).\n'
        '//\n'
        '// Inlined as data URIs for the same reason as season 1: Chrome will not\n'
        '// fetch a CSS mask-image over file://, so relative paths render blank\n'
        '// when you just double-click index.html.\n'
        'const ICON_URI = {\n' + '\n'.join(rows) + '\n};\n')
print(f'62 icons -> {OUT_JS} ({total / 1024:.0f} KB base64)')
